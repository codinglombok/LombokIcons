    ("x", {"color": "rgb(10 20 30 / 50%)"}, '<span class="lf" style="--lf-color:rgb(10 20 30 / 50%)">' + SVG_OPEN + ' aria-hidden="true" focusable="false"><path d="' + X + '"/></svg></span>', None),
    ("x", {"color": "oklch(0.7 0.1 200)"}, '<span class="lf" style="--lf-color:oklch(0.7 0.1 200)">' + SVG_OPEN + ' aria-hidden="true" focusable="false"><path d="' + X + '"/></svg></span>', None),
