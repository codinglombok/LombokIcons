#!/usr/bin/env python3
"""Builds vectors/lombokicons-vectors-v1.json (GP-11).

Expected outputs come from an independent Python implementation of the rendering
template in SPEC_LombokIcons section 3, written from the SPEC and not from the
JavaScript code, plus hand-written cases for options, escaping and validation.
The JavaScript build must reproduce every case byte for byte.

After editing, run:

    python3 vectors/build_vectors.py
    sha256sum vectors/lombokicons-vectors-v1.json > vectors/SHA256SUMS

and update the hash in docs/SPEC_LombokIcons_v<version>.md.
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
registry = json.loads((ROOT / "src" / "icons.json").read_text(encoding="utf-8"))
ICONS = registry["icons"]

RE_SIZE = re.compile(r"^(?:0|[0-9]+(?:\.[0-9]+)?(?:px|em|rem|%|vw|vh|vmin|vmax|pt|ch|ex))$")
RE_COLOR = re.compile(
    r"^(?:#[0-9a-fA-F]{3,8}|[a-zA-Z]{3,30}|(?:rgb|rgba|hsl|hsla|hwb|lab|lch|oklab|oklch|color)\([0-9a-zA-Z.,% /+-]{1,64}\)"
    r"|var\(--[a-zA-Z0-9_-]{1,64}\))$"
)
SVG_OPEN = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
            'stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"')


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;").replace("'", "&#39;")


def render(name, opts=None):
    """SPEC §3, implemented independently."""
    opts = opts or {}
    icon = ICONS.get(name)
    if icon is None:
        return ""
    mode = opts.get("mode") if opts.get("mode") in ("line", "bold", "duo") else "line"
    cls = opts.get("class")
    cls = " ".join(re.split(r"[ \t\n\f\r]+", cls.strip(" \t\n\f\r"))) if isinstance(cls, str) else ""
    styles = []
    if isinstance(opts.get("size"), str) and RE_SIZE.fullmatch(opts["size"]):
        styles.append("--lf-size:" + opts["size"])
    if isinstance(opts.get("color"), str) and RE_COLOR.fullmatch(opts["color"]):
        styles.append("--lf-color:" + opts["color"])
    title = opts.get("title") if isinstance(opts.get("title"), str) else ""
    out = '<span class="lf' + (" " + esc(cls) if cls else "") + '"'
    if styles:
        out += ' style="' + esc(";".join(styles)) + '"'
    out += ">" + SVG_OPEN
    out += (' role="img" aria-label="' + esc(title) + '">' + "<title>" + esc(title) + "</title>") if title else ' aria-hidden="true" focusable="false">'
    if mode == "duo" and icon["duo_accent"]:
        out += '<path d="' + icon["duo_accent"] + '" class="lf-accent" fill="currentColor" opacity="0.32" stroke="none"/>'
    out += '<path d="' + icon["line"] + '"/>'
    if mode == "bold" and icon["bold_accent"]:
        out += '<path d="' + icon["bold_accent"] + '" class="lf-bold-fill" fill="currentColor" stroke="none"/>'
    return out + "</svg></span>"


cases = []


def add(name, opts, expected, note=None):
    case = {"id": f"render-{len(cases) + 1:03d}", "fn": "renderIcon", "name": name}
    if opts:
        case["options"] = opts
    if note:
        case["note"] = note
    case["expected"] = expected
    cases.append(case)


# 1) every icon in every mode with default options (generated by the Python implementation)
for name in ICONS:
    for mode in ("line", "bold", "duo"):
        add(name, {"mode": mode}, render(name, {"mode": mode}))

# 2) hand-written option cases (expected strings typed out, checked against the Python implementation)
HOME = ICONS["home"]["line"]
X = ICONS["x"]["line"]
