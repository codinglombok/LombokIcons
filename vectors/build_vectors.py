    ("x", {"size": "2rem", "color": "#000"}, '<span class="lf" style="--lf-size:2rem;--lf-color:#000">' + SVG_OPEN + ' aria-hidden="true" focusable="false"><path d="' + X + '"/></svg></span>', "size before color"),
