for name, opts, expected, note in HAND:
    independent = render(name, opts)
    assert independent == expected, f"hand-written case disagrees with SPEC implementation: {name} {opts}\n{independent}\n{expected}"
    add(name, opts, expected, note)

doc = {
    "name": "lombokicons-vectors",
    "version": 1,
    "spec": "docs/SPEC_LombokIcons (section 3)",
    "icons_sha256_source": "src/icons.json",
    "functions": {"renderIcon": "renderIcon(case.name, case.options) -> string"},
    "cases": cases,
}
out = pathlib.Path(__file__).with_name("lombokicons-vectors-v1.json")
out.write_text(json.dumps(doc, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
print(f"{len(cases)} cases -> {out}")
