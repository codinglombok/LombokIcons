    ("constructor", None, "", "prototype keys are not icons"),
    ("x", {"mode": "sparkle"}, '<span class="lf">' + SVG_OPEN + ' aria-hidden="true" focusable="false"><path d="' + X + '"/></svg></span>', "unknown mode falls back to line"),
    ("x", {"class": "lf-xl  lf-spin "}, '<span class="lf lf-xl lf-spin">' + SVG_OPEN + ' aria-hidden="true" focusable="false"><path d="' + X + '"/></svg></span>', "class whitespace collapsed"),
    ("x", {"class": '" onmouseover="alert(1)'}, '<span class="lf &quot; onmouseover=&quot;alert(1)">' + SVG_OPEN + ' aria-hidden="true" focusable="false"><path d="' + X + '"/></svg></span>', "class escaped"),
